_STATION_SUFFIX_RE = re.compile(r"(火车站|高铁站|南站|北站|东站|西站|站)$")


def normalize_province(token: str | None) -> str:
    """将省份输入（如‘山东省’‘山东’‘广西壮族自治区’）归一为标准短名。"""
    s = re.sub(r"\s+", "", str(token or ""))
    if not s:
        return ""
    if s in ALL_PROVINCES_SET:
        return s
    if s in PROVINCE_ALIASES:
        return PROVINCE_ALIASES[s]
    s_short = _CITY_SUFFIX_RE.sub("", s)
    if s_short in ALL_PROVINCES_SET:
        return s_short
    return s


def _lookup_city_entry(token: str | None) -> tuple[str, float, float] | None:
    s = re.sub(r"\s+", "", str(token or ""))
    if not s:
        return None
    if s in CITY_CENTROIDS:
        return CITY_CENTROIDS[s]
    if s in COUNTY_OR_STATION_TO_CITY:
        return CITY_CENTROIDS.get(COUNTY_OR_STATION_TO_CITY[s])
    stripped = _CITY_SUFFIX_RE.sub("", s)
    if stripped in CITY_CENTROIDS:
        return CITY_CENTROIDS[stripped]
    if stripped in COUNTY_OR_STATION_TO_CITY:
        return CITY_CENTROIDS.get(COUNTY_OR_STATION_TO_CITY[stripped])
    # 自治州常见全称截前缀（如“黔东南苗族侗族自治州”、“延边朝鲜族自治州”）
    for key in _PREFIX_SEARCH_KEYS:
        if len(key) >= 2 and s.startswith(key):
            if key in CITY_CENTROIDS:
                return CITY_CENTROIDS[key]
            if key in COUNTY_OR_STATION_TO_CITY:
                return CITY_CENTROIDS.get(COUNTY_OR_STATION_TO_CITY[key])
    return None


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2.0 * r * math.asin(min(1.0, math.sqrt(a)))


def infer_station_province(
    station_name: str | None,
    city_name: str | None = None,
    lat: float | None = None,
    lon: float | None = None,
) -> str:
    """不依赖网络与强制坐标，综合 city 列、站名缀词及（若存在的）经纬度推断所属省级行政区。"""
    # 1) 显式省份/直辖市名或全称（注意避开 青海海南州）
    c_raw = re.sub(r"\s+", "", str(city_name or ""))
    if c_raw:
        if c_raw in PROVINCE_ALIASES:
            return PROVINCE_ALIASES[c_raw]
        if c_raw in ("北京", "天津", "上海", "重庆", "香港", "澳门", "吉林"):
            return c_raw
        ent = _lookup_city_entry(c_raw)
        if ent is not None:
            return ent[0]
        if c_raw in ALL_PROVINCES_SET:
            return c_raw

    # 2) 优先查精确中国铁路站名表（避免无 city 时被前缀误匹配，如 海北/平湖/东方红/镇江关），再用去后缀与最长前缀查城市/县级映射
    n_raw = re.sub(r"\s+", "", str(station_name or ""))
    if n_raw:
        n_core = _STATION_SUFFIX_RE.sub("", n_raw) or n_raw
        p_exact = _STATION_NAME_TO_PROVINCE.get(n_raw) or _STATION_NAME_TO_PROVINCE.get(n_core)
        if p_exact:
            return p_exact
        ent = _lookup_city_entry(n_raw) or _lookup_city_entry(n_core)
        if ent is not None:
            return ent[0]
        if len(n_core) >= 2:
            # 试探常见单字方位后缀剥离（威海北/杭州东/延平西/建阳北 -> 威海/杭州/延平/建阳）
            n_dir = re.sub(r"[东南西北中]$", "", n_core)
            if len(n_dir) >= 2:
                p_dir = _STATION_NAME_TO_PROVINCE.get(n_dir)
                if p_dir:
                    return p_dir
                ent = _lookup_city_entry(n_dir)
                if ent is not None:
                    return ent[0]

    # 3) 若站点已含有效坐标，兜底找 220km 内最近地级市质心所属省份
    if lat is not None and lon is not None:
        try:
            la, lo = float(lat), float(lon)
            if 15.0 <= la <= 55.0 and 72.0 <= lo <= 136.0:
                best_p = ""
                best_d = 220.0
                for p, cla, clo in CITY_CENTROIDS.values():
                    d = _haversine_km(la, lo, cla, clo)
                    if d < best_d:
                        best_d = d
                        best_p = p
                if best_p:
                    return best_p
        except (TypeError, ValueError):
            pass

    return ""


def _resolve_endpoint_point(query: str | None, stations: list[dict] | None = None) -> tuple[float, float, list[str]]:
    """提取起/终点的代表经纬度及涵盖省份列表（优先用库内站点坐标/city，缺省退用静态城市字典）。"""
    lats, lons, provs = [], [], []
    seen_p = set()
    for s in (stations or ()):
        nm = s.get("name") or ""
        ct = s.get("city") or ""
        la, lo = s.get("lat"), s.get("lon")
        p = infer_station_province(nm, ct, la, lo)
        if p and p not in seen_p:
            seen_p.add(p)
            provs.append(p)
        if la is not None and lo is not None:
            try:
                fla, flo = float(la), float(lo)
                if 15.0 <= fla <= 55.0 and 72.0 <= flo <= 136.0:
                    lats.append(fla)
                    lons.append(flo)
                    continue
            except (TypeError, ValueError):
                pass
        ent = _lookup_city_entry(ct) or _lookup_city_entry(nm)
        if ent is not None:
            lats.append(ent[1])
            lons.append(ent[2])

    if (not lats or not provs) and query:
        for tok in re.split(r"[,，;/\s]+", str(query).strip()):
            tok = tok.strip()
            if not tok:
                continue
            head = tok.split(":", 1)[0]
            ent = _lookup_city_entry(head) or _lookup_city_entry(tok)
            if ent is not None:
                if ent[0] not in seen_p:
                    seen_p.add(ent[0])
                    provs.append(ent[0])
                lats.append(ent[1])
                lons.append(ent[2])
            else:
                np = normalize_province(head)
                if np in ALL_PROVINCES_SET and np not in seen_p:
                    seen_p.add(np)
                    provs.append(np)

    if not lats:
        return (0.0, 0.0, provs)
    return (sum(lats) / len(lats), sum(lons) / len(lons), provs)


def recommend_corridor_provinces(
    from_q: str,
    to_q: str,
    from_stations: list[dict] | None = None,
    to_stations: list[dict] | None = None,
    widen: str = "standard",
) -> dict:
    """按起终点大圆走廊与可调侧向宽度推荐沿途经过省份（仅作填表建议，完全交由用户确认/修改）。"""
    f_lat, f_lon, f_provs = _resolve_endpoint_point(from_q, from_stations)
    t_lat, t_lon, t_provs = _resolve_endpoint_point(to_q, to_stations)
    if f_lat == 0.0 or t_lat == 0.0:
        combined = []
        for p in f_provs + t_provs:
            if p and p not in combined:
                combined.append(p)
        return {
            "ok": False,
            "provinces": combined,
            "from_provinces": f_provs,
            "to_provinces": t_provs,
            "od_km": 0.0,
            "slack_km": 0.0,
            "widen": widen,
            "note": "未识别起终点的地理坐标/城市归属，请先选择已知城市或手动勾选省份",
        }

    od_km = _haversine_km(f_lat, f_lon, t_lat, t_lon)
    w_norm = str(widen or "standard").strip().lower()
    if w_norm == "tight":
        half_width_km = max(140.0, min(250.0, od_km * 0.18))
    elif w_norm == "wide":
        half_width_km = max(350.0, min(560.0, od_km * 0.38))
    else:
        w_norm = "standard"
        half_width_km = max(230.0, min(370.0, od_km * 0.26))

    # 各向同性（经度按 cos(avg_lat) 缩放为真实公里投影）沿线进度 + 垂直偏航距离筛选：
    # 避免“椭圆形松弛量过大”把始发身后(如厦门去山东时的广东)或隔海(台湾/辽东半岛)误纳入推荐。
    cos_lat = math.cos(math.radians((f_lat + t_lat) * 0.5))
    kx = 111.32 * cos_lat
    ky = 110.57
    vx = (t_lon - f_lon) * kx
    vy = (t_lat - f_lat) * ky
    seg_len2 = max(1e-6, vx * vx + vy * vy)
    seg_len = math.sqrt(seg_len2)

    ep_set = set(f_provs) | set(t_provs)
    prov_best_prog: dict[str, float] = {}
    for p, cla, clo in CITY_CENTROIDS.values():
        if p == "台湾" and "台湾" not in ep_set:
            continue
        if p == "海南" and "海南" not in ep_set:
            continue
        if p in ("香港", "澳门") and not (ep_set & {"香港", "澳门", "广东"}):
            continue
        px = (clo - f_lon) * kx
        py = (cla - f_lat) * ky
        prog = (px * vx + py * vy) / seg_len2
        if prog < -0.02 or prog > 1.02:
            continue
        perp_km = abs(px * vy - py * vx) / seg_len
        if perp_km <= half_width_km:
            if p not in prov_best_prog or prog < prov_best_prog[p]:
                prov_best_prog[p] = prog

    for p in f_provs:
        prov_best_prog.setdefault(p, -0.05)
    for p in t_provs:
        prov_best_prog.setdefault(p, 1.05)

    ordered = [p for p, _ in sorted(prov_best_prog.items(), key=lambda x: (x[1], x[0]))]
    return {
        "ok": True,
        "provinces": ordered,
        "from_provinces": f_provs,
        "to_provinces": t_provs,
        "od_km": round(od_km, 1),
        "half_width_km": round(half_width_km, 1),
        "widen": w_norm,
    }


